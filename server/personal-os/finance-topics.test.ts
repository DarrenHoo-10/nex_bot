it('keeps finance identity stable, creates independent topics and durable FIFO input, isolates reads and cancels',async()=>{
 const dir=mkdtempSync(path.join(tmpdir(),'nex-finance-topics-')),key=randomBytes(32),fake=await startFakeModel();
 const options={dir,key,token:'fixture',identity:false as const,hostDevice:false as const,memoryRuntime:false as const,modelCatalog:{fetchDisabled:true}};
 let app=await createPersonalApp(options);
 try {
  app.runtime.kick=()=>{};
  app.store.saveConfig({provider:'openai',endpoint:fake.origin+'/v1',model:'fake',apiKey:'synthetic'});
  const {botId}=app.agents.finance();
  expect(app.agents.finance().botId).toBe(botId);
  expect(app.store.get('SELECT mode FROM agent_approval_settings WHERE bot_id=?',botId)?.mode).toBe('full');
  const a=app.agents.send(botId,'first topic','a',undefined,{newConversation:true});
  const b=app.agents.send(botId,'second topic','b',undefined,{newConversation:true});
  expect(a.conversationId).not.toBe(b.conversationId); expect(a.taskId).not.toBe(b.taskId);
  expect(app.agents.send(botId,'first topic','a',undefined,{newConversation:true})).toEqual(a);
  expect(()=>app.agents.send(botId,'different','a',undefined,{newConversation:true})).toThrow();
  const follow=app.agents.send(botId,'follow one','a2',undefined,{conversationId:a.conversationId});
  const follow2=app.agents.send(botId,'follow two','a3',undefined,{conversationId:a.conversationId});
  expect(follow.taskId).toBeNull(); expect(follow2.taskId).toBeNull();
  app.runtime.finishTask(a.taskId!,'succeeded','done'); await Promise.resolve();
  const receipt=app.store.get('SELECT * FROM agent_topic_inputs WHERE client_id=?','a2')!;
  expect(receipt.task_id).not.toBeNull(); expect(receipt.task_id).not.toBe(a.taskId);
  expect(app.store.get('SELECT task_id FROM agent_topic_inputs WHERE client_id=?','a3')?.task_id).toBeNull();
  app.agents.publish(botId,'assistant','message','answer A','answer-a',receipt.task_id);
  app.agents.publish(botId,'assistant','message','answer B','answer-b',b.taskId);
  expect(app.agents.topicMessages(botId,a.conversationId).some(m=>m.content==='answer B')).toBe(false);
  app.agents.read(botId,999,a.conversationId);
  expect(app.agents.topics(botId).find(t=>t.conversationId===b.conversationId)?.unread_count).toBe(1);
  app.agents.cancelTopic(botId,a.conversationId);
  expect(app.store.get('SELECT status FROM agent_topic_inputs WHERE client_id=?','a3')?.status).toBe('cancelled');
  expect(app.store.get('SELECT ended_at FROM tasks WHERE id=?',b.taskId)?.ended_at).toBeNull();
  const other=app.store.createBot('other'); expect(()=>app.agents.topicMessages(other,a.conversationId)).toThrow();
  const pub=app.agents.send(botId,'public research','public',undefined,{newConversation:true,audience:'public'});
  expect(()=>app.runtime.assertTopicTool(pub.taskId!,'memory.read',{documentId:'private'})).toThrow();
  expect(()=>app.runtime.assertTopicTool(pub.taskId!,'device.read',{})).toThrow();
  expect(()=>app.runtime.assertTopicTool(pub.taskId!,'connector.call',{connectorId:'generic'})).toThrow();
  const prompt=app.runtime.promptParts(pub.taskId!); expect(prompt.systemPrompt).toContain('public');
  const job=app.jobs.start({botId,title:'public background',sources:['message:'+pub.messageId],originTaskId:pub.taskId!,sourceKey:'public-job'});
  expect(app.runtime.isTopicTask(job.taskId)?.audience).toBe('public');
  expect(()=>app.runtime.assertTopicTool(job.taskId,'device.read',{})).toThrow();
  expect(()=>app.runtime.assertTopicTool(pub.taskId!,'job.message',{jobId:job.jobId})).not.toThrow();
  expect(()=>app.runtime.assertTopicTool(b.taskId!,'job.message',{jobId:job.jobId})).toThrow();
  expect(()=>app.jobs.start({botId,title:'bad source',sources:['message:'+b.messageId],originTaskId:pub.taskId!,sourceKey:'bad-public-job'})).toThrow();
  app.agents.cancelTopic(botId,pub.conversationId);
  expect(app.store.get('SELECT status FROM tasks WHERE id=?',job.taskId)?.status).toBe('cancelled');
  const c=app.agents.send(botId,'edit source','edit-source',undefined,{newConversation:true});
  const pending=app.agents.send(botId,'pending old','edit-pending',undefined,{conversationId:c.conversationId});
  const edited=app.agents.editTopic(botId,c.conversationId,pending.messageId,'pending corrected','edit-request');
  expect(app.store.get('SELECT status FROM agent_topic_inputs WHERE message_id=?',pending.messageId)?.status).toBe('cancelled');
  expect(app.agents.editTopic(botId,c.conversationId,pending.messageId,'pending corrected','edit-request')).toEqual(edited);
  expect(()=>app.agents.editTopic(botId,c.conversationId,pending.messageId,'different','edit-request')).toThrow();
  app.runtime.finishTask(c.taskId!,'failed','safe failure');
  const retried=app.agents.retryTopic(botId,c.conversationId,c.taskId!,'safe-retry'); expect(retried.conversationId).toBe(c.conversationId);
  const legacy=app.agents.send(botId,'legacy','l'.repeat(180)); expect(legacy.conversationId).not.toBe(pub.conversationId);
  const response=await fetch(app.origin+'/api/agents/messages?bot='+botId+'&conversationId='+b.conversationId,{headers:{Authorization:'Bearer fixture'}});
  expect(response.ok).toBe(true); expect(JSON.stringify(await response.json())).not.toContain('answer A');
  const runningChild=app.jobs.start({botId,title:'child of failed parent',prompt:'synthetic child',originTaskId:b.taskId!,sourceKey:'active-child'});
  app.runtime.finishTask(b.taskId!,'failed','parent failed');
  expect(()=>app.agents.retryTopic(botId,b.conversationId,b.taskId!,'active-child-retry')).toThrow('子任务仍在进行');
  app.agents.cancelTopic(botId,b.conversationId);
  expect(app.store.get('SELECT status FROM tasks WHERE id=?',runningChild.taskId)?.status).toBe('cancelled');
  await app.close(); app=await createPersonalApp(options); app.runtime.kick=()=>{};
  expect(app.agents.finance().botId).toBe(botId); expect(app.agents.topics(botId)).toHaveLength(4);
 } finally {await app.close();await fake.close();rmSync(dir,{recursive:true,force:true});}
},30000);

it('runs independent finance conversations through the real worker and keeps model context within each topic',async()=>{
 const dir=mkdtempSync(path.join(tmpdir(),'nex-finance-worker-')),fake=await startFakeModel();
 const app=await createPersonalApp({dir,key:randomBytes(32),token:'fixture',identity:false,hostDevice:false,memoryRuntime:false,modelCatalog:{fetchDisabled:true}});
 try {
  app.store.saveConfig({provider:'openai',endpoint:fake.origin+'/v1',model:'fake',apiKey:'synthetic'});
  const {botId}=app.agents.finance();
  app.runtime.memory.write(botId,{title:'private',content:'secret-account-value-93842'});
  fake.scripts.push({kind:'openai-text',text:'answer alpha'},{kind:'openai-text',text:'answer beta'});
  const a=app.agents.send(botId,'research alpha','worker-a',undefined,{newConversation:true});
  const b=app.agents.send(botId,'research beta','worker-b',undefined,{newConversation:true,audience:'public'});
  const deadline=Date.now()+25000;
  while((app.store.get('SELECT status FROM tasks WHERE id=?',a.taskId)?.status!=='succeeded'||app.store.get('SELECT status FROM tasks WHERE id=?',b.taskId)?.status!=='succeeded')&&Date.now()<deadline) await new Promise(r=>setTimeout(r,30));
  expect(app.store.get('SELECT status FROM tasks WHERE id=?',a.taskId)?.status).toBe('succeeded');
  expect(app.store.get('SELECT status FROM tasks WHERE id=?',b.taskId)?.status).toBe('succeeded');
  const prompts=fake.requests.filter(r=>r.url.includes('completions')).map(r=>r.body);
  expect(prompts.length).toBe(2);
  expect(prompts.every(p=>!p.includes('secret-account-value-93842'))).toBe(true);
  expect(prompts.filter(p=>p.includes('research alpha')).length).toBe(1);
  expect(prompts.filter(p=>p.includes('research beta')).length).toBe(1);
  expect(app.agents.topicMessages(botId,a.conversationId).filter(m=>m.role==='assistant')).toHaveLength(1);
  expect(app.agents.topicMessages(botId,b.conversationId).filter(m=>m.role==='assistant')).toHaveLength(1);
 }finally{await app.close();await fake.close();rmSync(dir,{recursive:true,force:true});}
},35000);

it('recovers durable FIFO after restart and refuses to replay a task with unknown business effects',async()=>{
 const dir=mkdtempSync(path.join(tmpdir(),'nex-finance-fifo-')),key=randomBytes(32),fake=await startFakeModel();
 const options={dir,key,token:'fixture',identity:false as const,hostDevice:false as const,memoryRuntime:false as const,modelCatalog:{fetchDisabled:true}};
 let app=await createPersonalApp(options),release=()=>{};
 try {
  app.runtime.kick=()=>{};app.store.saveConfig({provider:'openai',endpoint:fake.origin+'/v1',model:'fake',apiKey:'synthetic'});
  const {botId}=app.agents.finance(),a=app.agents.send(botId,'FIFO first','fifo-1',undefined,{newConversation:true});
  app.agents.send(botId,'FIFO second','fifo-2',undefined,{conversationId:a.conversationId});
  app.agents.send(botId,'FIFO third','fifo-3',undefined,{conversationId:a.conversationId});
  fake.scripts.push({kind:'openai-text',text:'first complete'},{kind:'openai-text',text:'second complete'},{kind:'openai-text',text:'third complete'});
  await app.close();app=await createPersonalApp(options);
  let deadline=Date.now()+25000;
  while(app.store.all("SELECT id FROM tasks WHERE status='succeeded'").length<3&&Date.now()<deadline)await new Promise(r=>setTimeout(r,30));
  expect(app.store.all('SELECT objective FROM tasks ORDER BY created_at,rowid').map(r=>r.objective)).toEqual(['FIFO first','FIFO second','FIFO third']);
  expect(app.store.all("SELECT status FROM agent_topic_inputs ORDER BY position").map(r=>r.status)).toEqual(['accepted','accepted','accepted']);
  for(let i=0;i<12;i++)fake.scripts.push({kind:'openai-tool',calls:[{id:'step-'+i,name:'broker',args:JSON.stringify({action:'tool.search',query:'connector'})}]});
  fake.scripts.push({kind:'openai-text',text:'Twelve steps completed'});
  const long=app.agents.send(botId,'multi-stage research','long-input',undefined,{newConversation:true});
  deadline=Date.now()+25000;while(app.store.get('SELECT ended_at FROM tasks WHERE id=?',long.taskId)?.ended_at===null&&Date.now()<deadline)await new Promise(r=>setTimeout(r,30));
  expect(app.store.get('SELECT status FROM tasks WHERE id=?',long.taskId)?.status).toBe('succeeded');
  expect(app.store.all('SELECT id FROM tool_calls WHERE task_id=?',long.taskId)).toHaveLength(12);
  const hold=new Promise<void>(resolve=>{release=resolve;});
  fake.scripts.push({kind:'openai-tool',calls:[{id:'effect',name:'broker',args:JSON.stringify({action:'memory.write',scope:'context',title:'工作笔记',content:'fixture note',expectedVersion:0})}]},{kind:'openai-text',text:'effect complete',waitFor:hold});
  const effect=app.agents.send(botId,'record this step','effect-input',undefined,{newConversation:true});
  deadline=Date.now()+20000;
  while(!app.store.get("SELECT id FROM tool_calls WHERE task_id=? AND status='succeeded'",effect.taskId)&&Date.now()<deadline)await new Promise(r=>setTimeout(r,30));
  expect(app.store.get("SELECT id FROM tool_calls WHERE task_id=? AND status='succeeded'",effect.taskId)).toBeTruthy();
  app.agents.cancelTopic(botId,effect.conversationId);release();
  deadline=Date.now()+5000;while(app.store.get('SELECT ended_at FROM tasks WHERE id=?',effect.taskId)?.ended_at===null&&Date.now()<deadline)await new Promise(r=>setTimeout(r,30));
  app.store.run("UPDATE tool_calls SET status='unknown' WHERE task_id=?",effect.taskId);
  expect(()=>app.agents.retryTopic(botId,effect.conversationId,effect.taskId!,'unsafe-retry')).toThrow('结果未知');
  expect(app.store.get('SELECT position FROM agent_topic_inputs WHERE client_id=?','unsafe-retry')).toBeUndefined();
 }finally{release();await app.close();await fake.close();rmSync(dir,{recursive:true,force:true});}
},50000);
