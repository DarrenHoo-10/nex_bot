import { build } from "esbuild";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { mkdirSync, readFileSync, writeFileSync, copyFileSync, realpathSync } from "node:fs";
import path from "node:path";
const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sdkPackage = realpathSync(path.join(repo, "node_modules/@trycua/cua-driver/package.json"));
const require = createRequire(sdkPackage), version = JSON.parse(readFileSync(sdkPackage, "utf8")).version;
if (version !== "0.28.2") throw new Error("Requalify computer runtime for this CUA SDK version");
const native = path.dirname(require.resolve("@trycua/cua-driver-win32-x64-msvc/package.json"));
const output = path.join(repo, "dist-personal/computer-runtime");
mkdirSync(path.join(output, "native"), { recursive: true });
for (const name of ["cua_driver_sdk.dll", "cua_driver_node_runtime.node", "node-runtime-NOTICE.md"]) copyFileSync(path.join(native, name), path.join(output, "native", name));
const bundle = path.join(output, "sdk.mjs");
await build({ stdin: { contents: 'export { CuaDriver } from "@trycua/cua-driver";', resolveDir: repo, loader: "js" }, bundle: true, platform: "node", target: "node22", format: "esm", outfile: bundle, banner: { js: "import { createRequire as nexNativeRequire } from 'node:module'; const require = nexNativeRequire(import.meta.url);" } });
const source = readFileSync(bundle, "utf8"), pattern = /function resolveLibPath\d*\(opts\) \{/g;
const matches = source.match(pattern) ?? [];
if (matches.length !== 1) throw new Error("CUA SDK native resolver changed");
writeFileSync(bundle, source.replace(pattern, matches[0] + "\n if (process.env.OPENMAUSBOT_CUA_SDK_LIBRARY) return resolveOverride(opts.crateName, process.env.OPENMAUSBOT_CUA_SDK_LIBRARY);"));
writeFileSync(path.join(output, "NOTICE.txt"), "CUA Driver SDK 0.28.2, MIT license. https://github.com/trycua/cua\nNative Node runtime notice in native/node-runtime-NOTICE.md.\n");
console.log("Personal computer runtime staged", version);
