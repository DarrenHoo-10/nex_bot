// Keep the native asset catalog byte-identical to the web artwork and metadata.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { graphicAvatarIds } from "../shared/personal-appearance.ts";
import { graphicAvatarData } from "../shared/personal-graphic-avatars.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
async function output(relative, value) {
  const target = path.join(root, relative);
  const bytes = Buffer.from(value);
  if (check) {
    if (!bytes.equals(await readFile(target))) throw new Error(`Avatar catalog is stale: ${relative}`);
  } else {
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, bytes);
  }
}
const entries = graphicAvatarIds.map(id => ({ id, ...graphicAvatarData[id] }));
const rows = entries.map(({ id, description, sheet, crop, motion }) => {
  const [x, y, width, height] = crop;
  if (x < 0 || y < 0 || width <= 0 || height <= 0 || x + width > sheet.width || y + height > sheet.height
      || !motion.every(Number.isFinite) || motion[0] <= 0) throw new Error(`Invalid avatar: ${id}`);
  return `        .init(id: "${id}", description: "${description}", assetName: "graphic-${sheet.id}", sheetWidth: ${sheet.width}, sheetHeight: ${sheet.height}, x: ${x}, y: ${y}, width: ${width}, height: ${height}, tempo: ${motion[0]}, tilt: ${motion[1]}, lift: ${motion[2]}),`;
});
await output("apps/apple/Packages/NexClientKit/Sources/NexClientKit/Support/GraphicAvatarCatalog.swift", `// Generated by scripts/sync-graphic-avatars.mjs; edit shared/personal-graphic-avatars.ts.
import Foundation

public struct GraphicAvatarDescriptor: Sendable, Identifiable {
    public let id: String, description: String, assetName: String
    public let sheetWidth: Double, sheetHeight: Double
    public let x: Double, y: Double, width: Double, height: Double
    public let tempo: Double, tilt: Double, lift: Double
}

extension AvatarCatalog {
    public static let graphics: [GraphicAvatarDescriptor] = [
${rows.join("\n")}
    ]
    public static func graphic(_ id: String) -> GraphicAvatarDescriptor? { graphics.first { $0.id == id } }
}
`);
for (const sheet of new Map(entries.map(e => [e.sheet.id, e.sheet])).values()) {
  const dir = `apps/apple/Shared/Assets.xcassets/graphic-${sheet.id}.imageset`;
  await output(`${dir}/${sheet.id}.png`, await readFile(path.join(root, `src/personal/avatars/graphic/${sheet.id}.png`)));
  await output(`${dir}/Contents.json`, JSON.stringify({ images: [{ filename: `${sheet.id}.png`, idiom: "universal" }], info: { author: "xcode", version: 1 } }, null, 2) + "\n");
}
console.log(`${check ? "Verified" : "Synced"} ${entries.length} graphic avatars and 3 original sheets for web, Android, macOS and iOS.`);
